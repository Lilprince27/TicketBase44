const TK_LOCAL_FORMATTED = getFormattedDbEvents();

/**
 * Returns local override events if the query matches, otherwise null.
 */
export function getLocalOverride(query) {
  const normalized = query.trim().toLowerCase();
  // NFL Melbourne Game
  const nflResult = getNflOverride(query);
  if (nflResult) return nflResult;
  for (const [key, events] of Object.entries(LOCAL_EVENT_OVERRIDES)) {
    if (normalized.includes(key) || (normalized.length >= 3 && key.includes(normalized))) {
      const extra = normalized.replace(key, "").trim();
      if (extra.length >= 2) {
        const cityFiltered = events.filter(ev =>
          (ev.city || "").toLowerCase().includes(extra) ||
          (ev.venue || "").toLowerCase().includes(extra) ||
          (ev.localData?.venue_name || "").toLowerCase().includes(extra)
        );
        if (cityFiltered.length > 0) return cityFiltered;
      }
      return events;
    }
  }
  // AFL — filter matches by search term (team name, "grand final", etc.)
  if (AFL_KEYWORDS.some(k => normalized.includes(k))) {
    const filtered = AFL_MATCHES.filter(m =>
      m.title.toLowerCase().includes(normalized) ||
      (m.round || "").toLowerCase().includes(normalized)
    );
    if (filtered.length > 0) return filtered;
    return AFL_MATCHES;
  }
  // Ticketek events — return all events whose search keys match the query
  const matched = TK_LOCAL_FORMATTED.filter(ev => ev.keys.some(k => normalized.includes(k)));
  if (matched.length) return matched;
  return null;
}